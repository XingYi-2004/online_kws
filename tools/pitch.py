import numpy as np
from pyworld import stonemask, dio
from pyreaper import reaper

def pyworld_dio(x, hop_size, sampling_rate, min_f0, max_f0):
    dio_f0, _ = dio(np.double(x), sampling_rate, min_f0, max_f0, 
                    frame_period=hop_size/sampling_rate *1000)
    return dio_f0

def reaper_stonemask(x, hop_size, sampling_rate, min_f0, max_f0):
    """Extract f0 trajectary in each frame center with REAPER and StoneMask. 

    Args:
        x (float or double ndarray): [n_sample].
        hop_size (int).
        sampling_rate (int): in Hertz.
        min_f0 (int): in Hertz.
        max_f0 (int): in Hertz.

    Returns:
        fine_f0 (double ndarray): [n_frame]
    """
    x = np.squeeze(x).astype(np.double)
    n_frame = len(x) // hop_size
    n_sample = n_frame * hop_size
    x = x[:n_sample]
    int_x = np.clip(x * (65536 // 2), -32768, 32767).astype(np.int16)
    target_times = (
        np.linspace(0, n_frame - 1, n_frame) * hop_size / sampling_rate
        + hop_size / 2 / sampling_rate
    )
    _, _, reaper_times, reaper_f0, _ = reaper(
        int_x, sampling_rate, minf0=min_f0, maxf0=max_f0
    )
    coarse_f0 = np.interp(target_times, reaper_times, reaper_f0)
    fine_f0 = stonemask(x, coarse_f0, target_times, sampling_rate)
    return fine_f0


def reaper_gci(x, hop_size, sampling_rate, min_f0, max_f0):
    """Extract GCIs with REAPER

    Args:
        x (float or double ndarray): [n_sample].
        hop_size (int).
        sampling_rate (int): in Hertz.
        min_f0 (int): in Hertz.
        max_f0 (int): in Hertz.

    Returns:
        voiced_pmt (int ndarray): Voiced region pitch marks generated by REAPER [n_pitch_marks].
        scales (float ndarray): Voiced region pitch mark scales [n_pitch_marks].
    """
    x = np.squeeze(x).astype(np.double)
    n_frame = len(x) // hop_size
    n_sample = n_frame * hop_size
    x = x[:n_sample]
    int_x = np.clip(x * (65536 // 2), -32768, 32767).astype(np.int16)
    pmt, pm, reaper_times, reaper_f0, _ = reaper(
        int_x, sampling_rate, minf0=min_f0, maxf0=max_f0
    )
    voiced_pmt = pmt[pm > 0]
    voiced_pm_f0 = np.interp(voiced_pmt, reaper_times, reaper_f0)
    voiced_pm_scale = sampling_rate / voiced_pm_f0 / 2
    voiced_pmt = np.asanyarray(np.round(voiced_pmt * sampling_rate), dtype=np.int)
    return voiced_pmt, voiced_pm_scale